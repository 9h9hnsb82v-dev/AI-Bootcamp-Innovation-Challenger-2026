"""코드 가드레일(2026-11-18 사용자 승인 ③): 모델을 부르기 전에 권한·범위 밖 요청을 먼저 거절한다.

- 지시문만으로는 프롬프트 인젝션을 완전히 막지 못하므로(워크숍 자료 36쪽) 확실한 것은 코드에서 막는다.
- 거절 문장에는 항상 '도와드릴 수 없습니다'를 넣는다(화면 '거절' 배지·테스트 기준).
- 인계서: 제도·절차 설명은 통과(문서 검색으로 법령 근거 답변), 인계 데이터 분석·통계는 거절(범위 제외, MASTER_PROMPT v3.0).
- 키워드 규칙이라 놓치는 질문이 있을 수 있다 → 지시문 규칙과 함께 쓴다. 오탐을 줄이려고 '분석·통계' 같은 동사가 함께 있을 때만 거절한다.
"""
from __future__ import annotations

import re

RULES = [
    ("PERSONAL_ID", re.compile(r"\d{6}\s*-\s*[1-8]\d{6}|주민\s*(등록)?\s*번호"),
     "주민등록번호 같은 개인정보는 입력하지 마세요. 이 챗봇은 개인정보를 받지 않으므로 그 요청은 도와드릴 수 없습니다."),
    ("ACCOUNT", re.compile(r"(비밀\s*번호|패스워드|password|계정|아이디).{0,15}(초기화|알려|바꿔|변경해|찾아|해킹|뚫)", re.I),
     "다른 사람의 계정·비밀번호 관련 요청은 도와드릴 수 없습니다. 계정 문제는 관리자에게 문의하세요."),
    ("INJECTION", re.compile(r"((이전|앞|위|기존)의?\s*(지시|명령|규칙|프롬프트).{0,10}(무시|잊|따르지))|"
                             r"(시스템\s*프롬프트|system\s*prompt).{0,10}(보여|알려|출력|공개)|"
                             r"(관리자|개발자)\s*(모드|권한|처럼)|jailbreak", re.I),
     "지시를 바꾸거나 내부 설정을 공개하는 요청은 도와드릴 수 없습니다. 생산계획·폐기물·보관·수거·처리업체·법령 질문을 해 주세요."),
    ("HANDOVER_ANALYSIS",  # 범위 제외: 인계 데이터 분석·통계(제도 설명은 허용)
     re.compile(r"((인계서|인계\s*데이터|인계량|마감\s*인계|올바로).{0,20}(분석|통계|지역별|추이|합계|순위|몇\s*톤|처리방법별|비교|집계))|"  # 범위 제외 패턴
                r"((지역별|시도별|처리방법별).{0,10}(인계|처리량|처리방법))"),  # 범위 제외 패턴
     "폐기물 인계 데이터 분석·통계(지역별 인계량, 처리방법별 집계 등)는 이 서비스 범위가 아니라 도와드릴 수 없습니다. "  # 범위 제외 안내
     "인계서 제도나 전자인계 입력 기한 같은 법령 내용은 물어보시면 근거 조문과 함께 안내합니다."),
]


def precheck(text: str) -> dict | None:
    """거절해야 하면 {category, message}, 아니면 None."""
    t = text or ""
    for cat, rx, msg in RULES:
        if rx.search(t):
            return {"category": cat, "message": msg}
    return None
